import json
import logging

from services.ai.llm_client import chat_completion


logger = logging.getLogger(__name__)


class FilterGenerator:

    async def generate_filters(self, feed_name: str):

        prompt = f"""
Ты являешься AI-редактором персональных новостных лент Telegram.

Твоя задача — помочь пользователю создать умный фильтр новостей.

Пользователь вводит только название своей будущей новостной ленты:

"{feed_name}"


Твоя задача:

1. Проанализировать название ленты.
2. Определить, какую информацию вероятнее всего хочет получать пользователь.
3. Определить основную тему ленты.
4. Создать 3 разных варианта фильтрации новостей.


Важно:

Ты НЕ просто придумываешь названия фильтров.

Ты создаешь полноценные инструкции для другой AI-модели, которая позже будет читать реальные Telegram-посты и решать:
показывать пост пользователю или скрывать.


Каждый вариант фильтра должен иметь разный подход:


Вариант 1 — широкий фильтр:

Цель:
Получить много информации по теме.

Разрешает:
- большинство новостей по теме;
- новые события;
- обновления;
- обсуждения.

Минус:
может попадаться лишняя информация.


Вариант 2 — сбалансированный фильтр:

Цель:
Показывать только полезные и интересные новости.

Разрешает:
- важные события;
- практические материалы;
- значимые обновления;
- качественную аналитику.

Удаляет:
- спам;
- рекламу;
- повторяющиеся новости;
- малоинформативные сообщения.


Вариант 3 — строгий фильтр:

Цель:
Показывать только самые важные события.

Разрешает:
- крупные изменения;
- важные исследования;
- значимые релизы;
- события с большим влиянием.

Удаляет:
- мелкие новости;
- слухи;
- мнения без фактов;
- повторения.


Для каждого фильтра создай:

title:
Короткое название фильтра.

description:
Объяснение для пользователя.

strictness:
Строгость фильтра от 1 до 10.

ai_prompt:
Готовая инструкция для другой AI-модели.
Эта инструкция должна объяснять:
- какие посты показывать;
- какие посты скрывать;
- какие признаки важности учитывать.


Не используй общие фразы типа:
"показывать интересные новости"
"показывать полезную информацию"

Описывай конкретно.


Пример:

Название ленты:
"Искусственный интеллект"


Хороший результат:


title:
"Практический AI"


ai_prompt:
"Показывай новости о новых AI-инструментах, сервисах автоматизации, реальных примерах применения искусственного интеллекта в бизнесе и разработке. 
Игнорируй мемы, рекламу, общие рассуждения и повторные публикации."


Верни только JSON.

Формат:

{{
    "topic": "определенная тема",
    "filters": [
        {{
            "title": "",
            "description": "",
            "strictness": 1,
            "ai_prompt": ""
        }},
        {{
            "title": "",
            "description": "",
            "strictness": 1,
            "ai_prompt": ""
        }},
        {{
            "title": "",
            "description": "",
            "strictness": 1,
            "ai_prompt": ""
        }}
    ]
}}

Не добавляй никаких пояснений до или после JSON.
"""


        try:
            content = await chat_completion(
                messages=[{"role": "user", "content": prompt}],
                temperature=0.4,
                max_tokens=3000,
            )

            if not content:
                raise RuntimeError("Все AI-провайдеры недоступны")

            content = content.replace("```json", "").replace("```", "").strip()
            return json.loads(content)

        except Exception as e:

            logger.error(
                f"Filter generation error: {e}"
            )

            return {
                "topic": feed_name,
                "filters": [
                    {
                        "title": "Широкий",
                        "description": "Все новости по теме.",
                        "strictness": 3,
                        "ai_prompt": f"Показывай все новости по теме {feed_name}."
                    },
                    {
                        "title": "Сбалансированный",
                        "description": "Только важные и полезные новости.",
                        "strictness": 6,
                        "ai_prompt": f"Показывай только полезные и значимые новости по теме {feed_name}. Игнорируй рекламу и спам."
                    },
                    {
                        "title": "Строгий",
                        "description": "Только самые важные события.",
                        "strictness": 9,
                        "ai_prompt": f"Показывай только самые важные события по теме {feed_name}. Игнорируй второстепенные публикации."
                    }
                ]
            }